<?php

namespace App\Http\Controllers\Admin;

use App\Http\Controllers\Controller;
use App\Models\Branch;
use App\Services\AuditLogger;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\Rule;
use Illuminate\View\View;

class BranchController extends Controller
{
    /**
     * Display registered branches.
     */
    public function index(Request $request): View
    {
        $this->authorizeManagement($request);

        $query = Branch::query()->with('updatedBy');

        if ($request->filled('search')) {
            $search = trim((string) $request->input('search'));

            $query->where(function ($q) use ($search) {
                $q->where('branch_name', 'like', "%{$search}%")
                    ->orWhere('branch_code', 'like', "%{$search}%")
                    ->orWhere('city', 'like', "%{$search}%")
                    ->orWhere('state', 'like', "%{$search}%");
            });
        }

        if (in_array($request->input('status'), [
            'active',
            'inactive',
        ], true)) {
            $query->where(
                'status',
                $request->input('status')
            );
        }

        $branches = $query
            ->orderBy('branch_name')
            ->paginate(20)
            ->withQueryString();

        return view(
            'admin.branches.index',
            compact('branches')
        );
    }

    /**
     * Display the branch registration form.
     */
    public function create(Request $request): View
    {
        $this->authorizeManagement($request);

        return view('admin.branches.create');
    }

    /**
     * Register a new branch.
     *
     * Branch codes are generated automatically:
     * INT-B001, INT-B002, INT-B003...
     */
    public function store(Request $request): RedirectResponse
    {
        $this->authorizeManagement($request);

        $validated = $this->validatedData($request);

        DB::transaction(function () use ($validated, $request) {

            /*
             * Lock the existing business settings singleton
             * to serialize branch-code generation.
             *
             * This prevents two simultaneous requests from
             * receiving the same branch code, provided all
             * branch creation uses this controller.
             */
            $settings = DB::table('business_settings')
                ->where('id', 1)
                ->lockForUpdate()
                ->first();

            if (!$settings) {
                throw new \RuntimeException(
                    'Business settings must be initialized before registering branches.'
                );
            }

            /*
             * Generate the next branch code.
             */
            $branchCode = $this->generateBranchCode();

            /*
             * Create the branch record.
             *
             * The branch code is generated by the system,
             * never accepted from user input.
             */
            $branch = Branch::create([
                ...$validated,
                'branch_code' => $branchCode,
                'created_by' => $request->user()->id,
                'updated_by' => $request->user()->id,
            ]);

            /*
             * Record branch registration in Audit Logs.
             */
            AuditLogger::log(
                action: 'created',
                module: 'branches',
                description: 'Registered branch '
                    . $branch->branch_name
                    . ' (' . $branch->branch_code . ')',
                record: $branch,
                oldValues: [],
                newValues: $branch->getAttributes()
            );

        }, 3);

        return redirect()
            ->route('admin.branches.index')
            ->with(
                'success',
                'Branch registered successfully.'
            );
    }

    /**
     * Display the branch editing form.
     */
    public function edit(
        Request $request,
        Branch $branch
    ): View {
        $this->authorizeManagement($request);

        return view(
            'admin.branches.edit',
            compact('branch')
        );
    }

    /**
     * Update an existing branch.
     *
     * Branch codes remain unchanged.
     */
    public function update(
        Request $request,
        Branch $branch
    ): RedirectResponse {
        $this->authorizeManagement($request);

        $validated = $this->validatedData($request);

        DB::transaction(function () use (
            $validated,
            $request,
            $branch
        ) {
            $oldValues = $branch->only(
                array_keys($validated)
            );

            /*
             * Only validated fields can be updated.
             * branch_code is deliberately excluded.
             */
            $branch->fill($validated);

            $changes = $branch->getDirty();

            if (empty($changes)) {
                return;
            }

            $branch->updated_by = $request->user()->id;

            $branch->save();

            /*
             * Record the changed business fields.
             */
            AuditLogger::log(
                action: 'updated',
                module: 'branches',
                description: 'Updated branch '
                    . $branch->branch_name
                    . ' (' . $branch->branch_code . ')',
                record: $branch,
                oldValues: array_intersect_key(
                    $oldValues,
                    $changes
                ),
                newValues: $changes
            );

        }, 3);

        return redirect()
            ->route('admin.branches.index')
            ->with(
                'success',
                'Branch updated successfully.'
            );
    }

    /**
     * Validate branch registration and updates.
     *
     * branch_code is excluded because it is
     * generated automatically and cannot be edited.
     */
    private function validatedData(Request $request): array
    {
        return $request->validate([
            'branch_name' => [
                'required',
                'string',
                'max:150',
            ],

            'address' => [
                'nullable',
                'string',
                'max:255',
            ],

            'city' => [
                'nullable',
                'string',
                'max:100',
            ],

            'state' => [
                'nullable',
                'string',
                'max:100',
            ],

            'phone' => [
                'nullable',
                'string',
                'max:30',
            ],

            'email' => [
                'nullable',
                'email',
                'max:150',
            ],

            'status' => [
                'required',
                Rule::in([
                    'active',
                    'inactive',
                ]),
            ],

            'notes' => [
                'nullable',
                'string',
                'max:5000',
            ],
        ]);
    }

    /**
     * Generate the next branch identification code.
     *
     * Examples:
     * INT-B001
     * INT-B002
     * INT-B003
     * INT-B100
     * INT-B1000
     */
    private function generateBranchCode(): string
    {
        $latestNumber = Branch::query()
            ->where(
                'branch_code',
                'REGEXP',
                '^INT-B[0-9]+$'
            )
            ->selectRaw(
                'MAX(CAST(SUBSTRING(branch_code, 6) AS UNSIGNED)) AS last_number'
            )
            ->value('last_number');

        $nextNumber = ((int) $latestNumber) + 1;

        return 'INT-B' . str_pad(
            (string) $nextNumber,
            3,
            '0',
            STR_PAD_LEFT
        );
    }

    /**
     * Restrict branch management to the Owner.
     */
    private function authorizeManagement(
        Request $request
    ): void {
        abort_unless(
            $request->user()?->hasRole('owner'),
            403,
            'Only the Owner can manage branches.'
        );
    }
}
